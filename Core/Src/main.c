void HAL_FDCAN_RxFifo0Callback(FDCAN_HandleTypeDef *hfdcan, uint32_t RxFifo0ITs)
{
  if (!(RxFifo0ITs & FDCAN_IT_RX_FIFO0_NEW_MESSAGE)) return;

  HAL_FDCAN_GetRxMessage(hfdcan, FDCAN_RX_FIFO0, &RxHeader, RxData);

  if (RxHeader.Identifier == D_LOG_ID1)
  {
    for (int i = 0; i < 6; i++) serialnumber1[i] = RxData[i];
    loginrequest1 = 1;
    loggedin1 = 0;
  }
  else if (RxHeader.Identifier == D_LOG_ID2)
  {
    for (int i = 0; i < 6; i++) serialnumber2[i] = RxData[i];
    loginrequest2 = 1;
    loggedin2 = 0;
  }
  else if (RxHeader.Identifier == D_NORMAL_STATUS1)
  {
    for (int i = 0; i < 8; i++) msg1[i] = RxData[i];
    firstflag = 1;
    modules_disabled &= ~1;
  }
  else if (RxHeader.Identifier == D_NORMAL_STATUS2)
  {
    for (int i = 0; i < 8; i++) msg2[i] = RxData[i];
    secondflag = 1;
    modules_disabled &= ~2;
  }
  else if (RxHeader.Identifier == D_DISABLE_STATUS1)
  {
    modules_disabled |= 1;
  }
  else if (RxHeader.Identifier == D_DISABLE_STATUS2)
  {
    modules_disabled |= 2;
  }
}

